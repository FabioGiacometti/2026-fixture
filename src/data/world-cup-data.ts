function teamFlag(team: string): string {
  return TEAM_FLAGS[team] ?? "";
}

function getRegion(host: string): string {
  return HOST_REGION[host] ?? "Europa";
}

function getWinner(homeTeam: string, awayTeam: string, homeScore: number, awayScore: number, penalties?: { home: number; away: number }): string {
  if (homeScore > awayScore) return homeTeam;
  if (awayScore > homeScore) return awayTeam;
  if (penalties) return penalties.home > penalties.away ? homeTeam : awayTeam;
  return "Empate";
}

function getMatchEndMinute(note?: string, penalties?: { home: number; away: number }): number {
  if (penalties) return 120;
  if (note?.toLowerCase().includes("tiempo extra")) return 120;
  return 90;
}

function buildTimeline(scorers: Scorer[] | undefined, note?: string, penalties?: { home: number; away: number }): MatchTimelineItem[] {
  const endMinute = getMatchEndMinute(note, penalties);
  const timeline: MatchTimelineItem[] = [
    { minute: 0, type: "kickoff", description: "Inicio del partido" },
    { minute: 45, type: "halftime", description: "Descanso" },
    { minute: endMinute, type: "fulltime", description: "Final del partido" },
  ];

  if (scorers && scorers.length > 0) {
    scorers.forEach((scorer) => {
      timeline.push({
        minute: scorer.minute,
        type: "goal",
        team: scorer.team,
        description: `${scorer.team}: ${scorer.player}${scorer.penalty ? " (pen)" : ""}${scorer.ownGoal ? " (pp)" : ""}`,
      });
    });
  }

  if (penalties) {
    timeline.push({
      minute: endMinute + 1,
      type: "penalty-shootout",
      description: `Definición por penales ${penalties.home}-${penalties.away}`,
    });
  }

  return timeline.sort((a, b) => a.minute - b.minute);
}

