const mascotByYear: Record<number, string> = Object.entries(mascotModules).reduce(
  (acc, [path, module]) => {
    const match = path.match(/(\d{4})\.(png|jpg|jpeg|webp)$/i);
    if (!match) return acc;
    acc[Number(match[1])] = module.default;
    return acc;
  },
  {} as Record<number, string>
);

